import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
async function filesIn(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await filesIn(path));
    else if (entry.isFile() && path !== join(dist, 'sw.js')) result.push(path);
  }
  return result;
}
const files = (await filesIn(dist)).sort();
const paths = files.map((path) => relative(dist, path).split(sep).join('/'));
if (!paths.includes('index.html') || !paths.some((path) => path.startsWith('assets/'))) throw new Error('Build the Vite distribution before generating offline support.');
const hash = createHash('sha256');
// A change to worker behavior also creates a fresh cache, preserving the active
// offline build if installation of an updated worker cannot finish.
hash.update(await readFile(fileURLToPath(import.meta.url)));
for (let index = 0; index < files.length; index++) {
  hash.update(paths[index]); hash.update('\0'); hash.update(await readFile(files[index])); hash.update('\0');
}
const version = hash.digest('hex').slice(0, 20);
const precache = ['.', ...paths];
const worker = `/* Generated by scripts/build-sw.mjs. Original build: ${version}. */
const CACHE_PREFIX = 'dorvim-kitchen-offline-';
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(version)};
const URLS = ${JSON.stringify(precache)}.map((path) => new URL(path, self.registration.scope).href);
const INDEX_URL = new URL('index.html', self.registration.scope).href;
const ASSET_PATH = new URL('assets/', self.registration.scope).pathname;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      // addAll rejects unless every required file has a successful response.
      await cache.addAll(URLS.map((url) => new Request(url, { cache: 'reload', credentials: 'same-origin' })));
      const entries = await Promise.all(URLS.map((url) => cache.match(url)));
      if (entries.some((response) => !response || !response.ok)) throw new Error('Incomplete offline cache');
      await self.skipWaiting();
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      try {
        const response = await fetch(request);
        if (!response.ok) throw new Error('Navigation unavailable');
        event.waitUntil(Promise.all([cache.put(request, response.clone()), cache.put(INDEX_URL, response.clone())]).catch(() => {}));
        return response;
      } catch {
        return await cache.match(request, { ignoreVary: true }) || await cache.match(INDEX_URL, { ignoreVary: true }) || Response.error();
      }
    })());
    return;
  }
  if (!URLS.includes(url.href) && !url.pathname.startsWith(ASSET_PATH)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    // Public build assets are identical for module/non-module Origin headers.
    const stored = await cache.match(request, { ignoreVary: true });
    if (stored) return stored;
    const response = await fetch(request);
    if (response.ok) event.waitUntil(cache.put(request, response.clone()).catch(() => {}));
    return response;
  })());
});
`;
await writeFile(join(dist, 'sw.js'), worker);
console.log(`Offline cache ${version}: ${precache.length} local resources.`);
